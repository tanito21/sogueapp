def ruta_icono():
    """guarda el .ico en la carpeta temporal (si falta) y devuelve su ruta, o none si no se pudo."""
    datos = base64.b64decode(ICONO_BASE64)
    ruta = os.path.join(tempfile.gettempdir(), "sogueapp_icono.ico")
    try:
        if not os.path.exists(ruta) or os.path.getsize(ruta) != len(datos):
            with open(ruta, "wb") as archivo:
                archivo.write(datos)
    except OSError:
        return None
    return ruta


def poner_icono(ventana):
    """pone el ícono de sogue en la ventana y en la barra de tareas.

    customtkinter pone su ícono azul un instante después de abrir la ventana,
    por eso se vuelve a poner un poco después (250 y 700 ms).
    """
    ruta = ruta_icono()
    if ruta is None:
        return

    def aplicar():
        try:
            ventana.iconbitmap(ruta)
        except Exception:
            pass   # la ventana ya se cerró

    aplicar()
    ventana.after(250, aplicar)
    ventana.after(700, aplicar)
